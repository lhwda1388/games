  function melon(cx, by, w, h, light) {
    // ellipse with stripes; light=true draws the rare white melon with a dotted rind
    for (var j = 0; j < h; j++) {
      var yy = (j + 0.5 - h / 2) / (h / 2);
      var half = Math.round((w / 2) * Math.sqrt(Math.max(0, 1 - yy * yy)));
      if (half <= 0) continue;
      var y = by - h + j;
      px(cx - half, y, half * 2, 1, 4);
      if (j === 0 || j === h - 1 || half < 2) continue;
      for (var x = cx - half + 1; x < cx + half - 1; x++) {
        var c;
        if (light) c = ((x + j) % 4 === 0) ? 2 : 0;
        else c = ((x - cx + 64) % 3 === 0) ? 4 : 2;
        px(x, y, 1, 1, c);
      }
    }
    px(cx - Math.floor(w / 4), by - h + 2, 2, 1, light ? 1 : 0);
    px(cx, by - h - 2, 1, 2, 4);                 // stem
  }
  function pumpkin(cx, by, w, h) {
    // squat, pale, ribbed: reads apart from the dark striped melon
    for (var j = 0; j < h; j++) {
      var yy = (j + 0.5 - h / 2) / (h / 2);
      var half = Math.round((w / 2) * Math.sqrt(Math.max(0, 1 - yy * yy)));
      if (half <= 0) continue;
      var y = by - h + j;
      px(cx - half, y, half * 2, 1, 4);
      if (j === 0 || j === h - 1 || half < 2) continue;
      for (var x = cx - half + 1; x < cx + half - 1; x++) px(x, y, 1, 1, (Math.abs(x - cx) % 3 === 1) ? 3 : 1);
    }
    px(cx - 1, by - h - 2, 2, 3, 4); px(cx + 1, by - h - 2, 2, 1, 3);
  }
